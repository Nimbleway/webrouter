"""Regenerate the vendor tables in ``VENDORS.md`` and the vendor section of ``.env.example`` from the catalog.

Both are generated, so a new vendor file is never listed in one place and
missing from the other. Each generated part sits between markers; the prose
around it is hand-written and left alone.

    make vendors                                 # rewrite both
    uv run python -m scripts.vendors --check     # exit 1 if either is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

from web_router.constants_vendors import VENDOR_CATEGORIES, VENDOR_CATEGORY_DESCRIPTIONS
from web_router.vendors.catalog import VendorCatalog, get_catalog
from web_router.vendors.schema import Vendor

ROOT = Path(__file__).resolve().parent.parent
VENDORS_MD = ROOT / "VENDORS.md"
ENV_EXAMPLE = ROOT / ".env.example"

MD_OPEN, MD_CLOSE = "<!-- vendors -->", "<!-- /vendors -->"
ENV_OPEN = "# --- Vendor data (generated by `make vendors` from src/web_router/data/vendors) ---"
ENV_CLOSE = "# --- /Vendor data ---"


def _auth(vendor: Vendor) -> str:
    if vendor.auth.oauth2 is not None:
        return "OAuth refresh token"
    if vendor.auth.basic is not None:
        return "HTTP Basic"
    if not vendor.auth.credentials:
        return "none"
    places = {injection.location for injection in vendor.auth.inject}
    return "key in " + " and ".join(sorted(places)) if places else "key"


def _counts(vendor: Vendor) -> str:
    writes = sum(endpoint.writes for endpoint in vendor.endpoints)
    reads = len(vendor.endpoints) - writes
    return f"{reads} read" + (f", {writes} write" if writes else "")


def _verified(vendor: Vendor) -> str:
    live = [endpoint.verified.live for endpoint in vendor.endpoints if endpoint.verified.live]
    return f"live {max(live)}" if live else f"docs {vendor.curated}"


def markdown_table(catalog: VendorCatalog) -> str:
    by_category: dict[str, list[Vendor]] = defaultdict(list)
    for vendor in catalog.all():
        by_category[vendor.category].append(vendor)
    total = sum(len(vendor.endpoints) for vendor in catalog.all())
    lines = [f"{len(catalog)} vendors, {total} endpoints.", ""]
    for category in VENDOR_CATEGORIES:
        vendors = by_category.get(category)
        if not vendors:
            continue
        lines += [
            f"### {category}",
            "",
            VENDOR_CATEGORY_DESCRIPTIONS[category],
            "",
            "| Vendor | What it holds | Endpoints | Auth | Variables | Checked |",
            "|---|---|---|---|---|---|",
        ]
        for vendor in vendors:
            variables = ", ".join(f"`{spec.env[0]}`" for spec in vendor.auth.credentials.values()) or "none"
            lines.append(
                f"| [{vendor.name}]({vendor.docs_url}) `{vendor.vendor}` | {vendor.summary} | {_counts(vendor)} "
                f"| {_auth(vendor)} | {variables} | {_verified(vendor)} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def env_section(catalog: VendorCatalog, elsewhere: frozenset[str] = frozenset()) -> str:
    """The vendor section; a variable ``.env.example`` already sets for a backend is pointed to, not repeated."""
    lines = [ENV_OPEN, "# Keys for call_vendor(): each vendor's own API, with your account. All optional.", ""]
    for vendor in catalog.all():
        if not vendor.auth.credentials and not vendor.settings:
            continue
        lines.append(f"# {vendor.name} - {vendor.docs_url}")
        for spec in vendor.auth.credentials.values():
            if spec.env[0] in elsewhere:
                lines.append(f"#   uses {spec.env[0]} above")
            else:
                lines.append(f"{spec.env[0]}=")
        for name, setting in vendor.settings.items():
            default = f" (default {setting.default})" if setting.default else ""
            lines.append(f"# {setting.env[0]}=   # optional {name}{default}")
        lines.append("")
    lines.append(ENV_CLOSE)
    return "\n".join(lines) + "\n"


def _replace(text: str, start: str, end: str, body: str, *, inclusive: bool) -> str:
    if start not in text or end not in text:
        return text.rstrip("\n") + "\n\n" + (body if inclusive else f"{start}\n{body}{end}\n")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    if inclusive:
        return head + body.rstrip("\n") + tail
    return head + start + "\n" + body + end + tail


def regenerate_markdown(current: str, catalog: VendorCatalog) -> str:
    return _replace(current, MD_OPEN, MD_CLOSE, markdown_table(catalog), inclusive=False)


def regenerate_env(current: str, catalog: VendorCatalog) -> str:
    outside = current.split(ENV_OPEN, 1)[0] + (current.split(ENV_CLOSE, 1)[1] if ENV_CLOSE in current else "")
    elsewhere = frozenset(re.findall(r"^([A-Z][A-Z0-9_]*)=", outside, flags=re.MULTILINE))
    return _replace(current, ENV_OPEN, ENV_CLOSE, env_section(catalog, elsewhere), inclusive=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if VENDORS.md or .env.example is stale")
    args = parser.parse_args(argv)
    catalog = get_catalog()
    stale = []
    for path, regenerate in ((VENDORS_MD, regenerate_markdown), (ENV_EXAMPLE, regenerate_env)):
        current = path.read_text(encoding="utf-8")
        updated = regenerate(current, catalog)
        if updated != current:
            stale.append(path.name)
            if not args.check:
                path.write_text(updated, encoding="utf-8")
    if args.check and stale:
        print(f"{', '.join(stale)} stale: run `make vendors`.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
