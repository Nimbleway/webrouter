"""Build the Web Catalog tab of the docs site from the vendor catalog.

Each vendor's JSON file in ``src/web_router/data/vendors/`` is the only
source: this script turns it into a page per data API (see
:mod:`scripts.data_api_page`), the index the catalog page filters, and the
"Web Catalog" tab's sidebar, one collapsed group per category. Nothing
generated is committed: the script copies ``docs/`` to an output folder and
writes into the copy, which the ``docs-site`` workflow publishes on the branch
the docs site deploys from.

    make docs-site                               # build/docs-site/docs, ready for `mint dev`
    uv run python -m scripts.data_api_docs --out build/docs-site/docs
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

from scripts.data_api_page import DEFAULT_ICON, NO_PEERS, PAGES_DIR, Peers, category_label, icon_url, vendor_page
from web_router.constants_vendors import VENDOR_CATEGORIES, VENDOR_CATEGORY_DESCRIPTIONS
from web_router.vendors.catalog import VendorCatalog, builtin_catalog
from web_router.vendors.schema import Vendor, VendorEndpoint

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = ROOT / "build" / "docs-site" / "docs"

INDEX_FILE = "snippets/data-apis-index.jsx"
"""The gallery's data, under docs/: a named export, since Mintlify snippets cannot import JSON."""
TAB = "Web Catalog"
"""The docs.json tab the catalog lives in. Its first group's committed pages (the catalog page) stay first;
one collapsed group per category follows them."""


def job_peers(catalog: VendorCatalog) -> Peers:
    """Every endpoint by its vendor-neutral job, one per vendor, so a page can point to the others."""
    peers: dict[str, list[tuple[Vendor, VendorEndpoint]]] = defaultdict(list)
    for vendor in catalog.all():
        seen: set[str] = set()
        for endpoint in vendor.endpoints:
            if endpoint.job and endpoint.job not in seen and not endpoint.job.startswith(NO_PEERS):
                seen.add(endpoint.job)
                peers[endpoint.job].append((vendor, endpoint))
    return peers


def index_entries(catalog: VendorCatalog, icons: dict[str, str] | None = None) -> dict[str, Any]:
    """What the gallery filters: the categories in shelf order, and one small row per vendor."""
    vendors = sorted(catalog.all(), key=lambda vendor: vendor.name.lower())
    counts: dict[str, int] = defaultdict(int)
    for vendor in vendors:
        counts[vendor.category] += 1
    categories = [
        {
            "id": category,
            "label": category_label(category),
            "description": VENDOR_CATEGORY_DESCRIPTIONS[category],
            "count": counts[category],
        }
        for category in VENDOR_CATEGORIES
        if counts[category]
    ]
    rows = [
        {
            "id": vendor.vendor,
            "name": vendor.name,
            "category": vendor.category,
            "summary": vendor.summary,
            "icon": (icons or {}).get(vendor.vendor, DEFAULT_ICON),
            "endpoints": len(vendor.endpoints),
            # The catalog page's one fact per row: whether a call needs a key the user must set first.
            "needs_key": any(spec.required for spec in vendor.auth.credentials.values()),
            # Searched, not shown: what a visitor might type for this vendor besides its name.
            "terms": " ".join(
                [vendor.vendor, *vendor.sites, *(endpoint.name for endpoint in vendor.endpoints)]
            ).lower(),
        }
        for vendor in vendors
    ]
    return {"categories": categories, "vendors": rows}


def index_snippet(index: dict[str, Any]) -> str:
    data = json.dumps(index, ensure_ascii=False, separators=(",", ":"))
    header = "// Generated by scripts/data_api_docs.py from src/web_router/data/vendors."
    return f"{header}\nexport const DATA_APIS = {data};\n"


def with_catalog_tab(config: dict[str, Any], catalog: VendorCatalog) -> dict[str, Any]:
    """docs.json with the catalog tab's sidebar: its committed pages, then a collapsed group per category."""
    tabs = config.get("navigation", {}).get("tabs", [])
    tab = next((tab for tab in tabs if tab.get("tab") == TAB), None)
    if tab is None or not tab.get("groups"):
        raise SystemExit(f"docs.json has no {TAB!r} tab with a group to add the data API pages to")
    group = tab["groups"][0]
    kept = [page for page in group.get("pages", []) if isinstance(page, str)]
    by_category: dict[str, list[Vendor]] = defaultdict(list)
    for vendor in catalog.all():
        by_category[vendor.category].append(vendor)
    sections = [
        {
            "group": category_label(category),
            "expanded": False,
            "pages": [
                f"{PAGES_DIR}/{vendor.vendor}"
                for vendor in sorted(by_category[category], key=lambda vendor: vendor.name.lower())
            ],
        }
        for category in VENDOR_CATEGORIES
        if by_category.get(category)
    ]
    group["pages"] = kept + sections
    return config


def build(source: Path, docs: Path, catalog: VendorCatalog) -> int:
    """Copy ``source`` to ``docs`` and write the generated files into it; return how many vendor pages."""
    if docs.resolve() == source.resolve():
        raise SystemExit("--out must not be the committed docs folder: the generated pages are never committed")
    shutil.rmtree(docs, ignore_errors=True)
    shutil.copytree(source, docs)
    pages = docs / PAGES_DIR
    pages.mkdir(parents=True, exist_ok=True)
    peers = job_peers(catalog)
    vendors = sorted(catalog.all(), key=lambda vendor: vendor.vendor)
    icons = {vendor.vendor: icon_url(vendor.vendor, docs) for vendor in vendors}
    for vendor in vendors:
        (pages / f"{vendor.vendor}.mdx").write_text(vendor_page(vendor, peers, icons[vendor.vendor]), encoding="utf-8")
    index = docs / INDEX_FILE
    index.parent.mkdir(parents=True, exist_ok=True)
    index.write_text(index_snippet(index_entries(catalog, icons)), encoding="utf-8")
    config_path = docs / "docs.json"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    config = with_catalog_tab(config, catalog)
    config_path.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return len(vendors)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=OUT, help="where the built docs go (default: build/docs-site/docs)")
    args = parser.parse_args(argv)
    written = build(DOCS, args.out, builtin_catalog())  # never a local extra folder: the site shows what ships
    print(f"{written} data API pages written; the site is in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
