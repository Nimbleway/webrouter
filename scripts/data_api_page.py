"""One data API's page in the Web Catalog, rendered as MDX from its catalog entry.

The page is a header card, the setup, the vendor's notes, an index of its
endpoints, and one block per endpoint whose inputs and outputs sit apart: an
Input table always, and an Output panel only when the entry records what the
call returns (``example_response``). The blocks are plain JSX elements with
``wc-*`` classes (styled in ``docs/style.css``), so they render on the server
and stay in the site's search and ``llms.txt``; every catalog string in them is
escaped, since MDX reads braces, angle brackets and ``$`` as markup.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from scripts.vendors import _auth
from web_router.vendors.schema import Vendor, VendorEndpoint, VendorParam

PAGES_DIR = "data-apis"
"""Where the vendor pages go, under docs/: one ``<vendor>.mdx`` each, at ``/data-apis/<vendor>``."""
ICON_DIR = "logo/data-apis"
"""Under docs/: a vendor's icon is ``<vendor id>`` with one of ICON_SUFFIXES; without one, DEFAULT_ICON."""
ICON_SUFFIXES = (".svg", ".png", ".webp")
DEFAULT_ICON = f"/{ICON_DIR}/_default.svg"
PEERS_SHOWN = 6
NO_PEERS = ("account.",)
"""Jobs every vendor has (a credit balance), where pointing to the others helps no one."""
OUTPUT_DEPTH = 3
"""How deep the Output table follows an example response's nesting."""
OUTPUT_ROWS = 40

CATEGORY_LABELS = {"seo": "SEO", "ai": "AI", "company-data": "Company data"}
GENERATED_NOTE = "{{/* Generated by scripts/data_api_docs.py from src/web_router/data/vendors/{vendor}.json. */}}"

Peers = dict[str, list[tuple[Vendor, VendorEndpoint]]]


def category_label(category: str) -> str:
    return CATEGORY_LABELS.get(category, category.replace("-", " ").capitalize())


_ENTITIES = {
    "<": "&lt;",
    ">": "&gt;",
    "{": "&#123;",
    "}": "&#125;",
    "$": "&#36;",
    "\\": "&#92;",
}
"""Characters MDX reads as markup: tags, expressions and, on Mintlify, $math$. Entities, not backslashes,
since a backslash inside an autolinked URL is kept and the tag after it still parses."""
_UNSAFE = re.compile("[" + re.escape("".join(_ENTITIES)) + "]")


def _literal(value: str) -> str:
    """A JSX string expression: nothing in it is read as Markdown, a tag or math."""
    return "{" + json.dumps(value, ensure_ascii=False).replace("$", "\\u0024") + "}"


def text(value: str) -> str:
    """A catalog string as JSX children: plain runs as string literals, `code` spans as <code>."""
    parts = value.split("`")
    if len(parts) % 2 == 0:  # an unmatched backtick is just a character
        parts = [value]
    out = []
    for index, part in enumerate(parts):
        if not part:
            continue
        out.append(f"<code>{_literal(part)}</code>" if index % 2 else _literal(part))
    return "".join(out)


def mdx(value: str) -> str:
    """A catalog string as Markdown prose: markup characters as entities, `code` spans kept."""
    parts = value.split("`")
    for index in range(0, len(parts), 2):  # even parts are outside backticks
        parts[index] = _UNSAFE.sub(lambda match: _ENTITIES[match.group(0)], parts[index])
    if len(parts) % 2 == 0:  # an unmatched backtick: escape the rest as prose too
        parts[-1] = _UNSAFE.sub(lambda match: _ENTITIES[match.group(0)], parts[-1])
    return "`".join(parts)


def _code(value: object) -> str:
    return f"<code>{_literal(value if isinstance(value, str) else json.dumps(value, ensure_ascii=False))}</code>"


def _href(url: str) -> str:
    return json.dumps(url)


def anchor(endpoint_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", endpoint_id.lower()).strip("-")


def _method(method: str) -> str:
    return f'<span className="wc-method wc-method-{method.lower()}">{_literal(method)}</span>'


def _key_badge(vendor: Vendor) -> str:
    required = [spec.env[0] for spec in vendor.auth.credentials.values() if spec.required]
    if not vendor.auth.credentials:
        return f'<span className="wc-badge wc-badge-free">{_literal("No key needed")}</span>'
    if not required:
        return f'<span className="wc-badge">{_literal("Key optional")}</span>'
    names = _literal(", ").join(_code(name) for name in required)
    return f'<span className="wc-badge wc-badge-key">{_literal("Needs ")}{names}</span>'


def _stat(label: str, value: str) -> str:
    return (
        f'<div className="wc-stat"><span className="wc-stat-label">{_literal(label)}</span>'
        f'<span className="wc-stat-value">{value}</span></div>'
    )


def icon_url(vendor_id: str, docs: Path) -> str:
    """The site path of a vendor's icon in ``docs``, or the shared default when it has none."""
    for suffix in ICON_SUFFIXES:
        if (docs / ICON_DIR / f"{vendor_id}{suffix}").is_file():
            return f"/{ICON_DIR}/{vendor_id}{suffix}"
    return DEFAULT_ICON


def _header(vendor: Vendor, icon: str) -> list[str]:
    links = [f"<a href={_href(vendor.docs_url)}>{_literal('Vendor docs')}</a>"]
    if vendor.pricing_url:
        links.append(f"<a href={_href(vendor.pricing_url)}>{_literal('Pricing')}</a>")
    if vendor.sites:
        links.append(_literal("Serves ") + _literal(", ").join(_code(site) for site in vendor.sites))
    auth = _auth(vendor)
    return [
        '<div className="wc-vendor">',
        '<div className="wc-vendor-top">',
        '<span className="wc-vendor-id">'
        f'<img className="wc-icon" src={_href(icon)} alt="" width="40" height="40" noZoom />'
        f'<a className="wc-category" href="/{PAGES_DIR}?category={vendor.category}">'
        f"{_literal('Web Catalog · ' + category_label(vendor.category))}</a></span>",
        _key_badge(vendor),
        "</div>",
        '<div className="wc-stats">',
        _stat("Endpoints", text(str(len(vendor.endpoints)))),
        _stat("Auth", text("None" if auth == "none" else auth[0].upper() + auth[1:])),
        "</div>",
        f'<div className="wc-links">{_literal(" · ").join(links)}</div>',
        "</div>",
        "",
    ]


def _setup(vendor: Vendor) -> list[str]:
    if not vendor.auth.credentials and not vendor.settings:
        return []
    lines = ["## Setup", "", "| Variable | | What it is |", "|---|---|---|"]
    for spec in vendor.auth.credentials.values():
        need = "required" if spec.required else "some calls"
        lines.append(f"| `{spec.env[0]}` | {need} | {mdx(spec.description)} |")
    for name, setting in vendor.settings.items():
        default = f" Default `{setting.default}`." if setting.default else ""
        choices = f" One of {', '.join(f'`{choice}`' for choice in setting.choices)}." if setting.choices else ""
        lines.append(f"| `{setting.env[0]}` | optional | {mdx(setting.description or name)}{default}{choices} |")
    lines += [
        "",
        "Put them in your environment or `.env`; [Data APIs](/vendors) covers the other ways.",
        "",
    ]
    return lines


def _index(vendor: Vendor) -> list[str]:
    rows = [
        f'<a className="wc-index-row" href="#{anchor(endpoint.id)}">{_method(endpoint.method)}'
        f'<span className="wc-index-name">{text(endpoint.name)}</span>'
        f'<span className="wc-index-summary">{text(endpoint.summary)}</span></a>'
        for endpoint in vendor.endpoints
    ]
    return ['<div className="wc-index">', *rows, "</div>", ""]


def _input_row(name: str, param: VendorParam) -> str:
    notes = [text(param.description)] if param.description else []
    if param.enum:
        notes.append(_literal(" One of ") + _literal(", ").join(_code(choice) for choice in param.enum))
    if param.example is not None:
        notes.append(_literal(" Example ") + _code(param.example))
    required = f' <span className="wc-required">{_literal("required")}</span>' if param.required else ""
    return (
        f"<tr><td>{_code(name)}{required}</td><td>{_literal(param.type)}</td>"
        f"<td>{_literal(param.location)}</td><td>{''.join(notes)}</td></tr>"
    )


def _input_panel(endpoint: VendorEndpoint) -> list[str]:
    head = f'<div className="wc-panel"><div className="wc-panel-title">{_literal("Input")}</div>'
    if not endpoint.params:
        return [head, f'<p className="wc-none">{_literal("No inputs.")}</p>', "</div>"]
    return [
        head,
        '<table className="wc-table"><thead>'
        "<tr>"
        + "".join(f"<th>{_literal(name)}</th>" for name in ("Name", "Type", "In", "Notes"))
        + "</tr></thead><tbody>",
        *(_input_row(name, param) for name, param in endpoint.params.items()),
        "</tbody></table>",
        "</div>",
    ]


def _type_name(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, (int, float)):
        return "number"
    if isinstance(value, str):
        return "string"
    return "array" if isinstance(value, list) else "object"


def _leaf_type(value: Any) -> str:
    if isinstance(value, list):
        first = next((item for item in value if item is not None), None)
        return f"{_type_name(first)}[]" if first is not None else "array"
    return _type_name(value)


def output_fields(example: Any, prefix: str = "", depth: int = 0) -> list[tuple[str, str]]:
    """The fields an example response holds, as (path, type) -- ``items[].id`` for a list of objects."""
    if isinstance(example, list):
        first = next((item for item in example if item is not None), None)
        rows = [(prefix, _leaf_type(example))] if prefix else []
        if isinstance(first, (dict, list)) and depth < OUTPUT_DEPTH:
            rows += output_fields(first, f"{prefix}[]", depth + 1)
        return rows
    if isinstance(example, dict):
        rows = []
        for key, value in example.items():
            path = f"{prefix}.{key}" if prefix else str(key)
            if isinstance(value, (dict, list)) and depth < OUTPUT_DEPTH:
                if isinstance(value, dict):
                    rows.append((path, "object"))
                rows += output_fields(value, path, depth + 1)
            else:
                rows.append((path, _leaf_type(value)))
        return rows
    return [(prefix or "(body)", _type_name(example))]


def _output_panel(endpoint: VendorEndpoint) -> list[str]:
    if endpoint.example_response is None:
        return []
    fields = output_fields(endpoint.example_response)[:OUTPUT_ROWS]
    rows = [f"<tr><td>{_code(path)}</td><td>{_literal(kind)}</td></tr>" for path, kind in fields]
    return [
        f'<div className="wc-panel"><div className="wc-panel-title">{_literal("Output")}</div>',
        f'<table className="wc-table"><thead><tr><th>{_literal("Field")}</th><th>{_literal("Type")}</th></tr>'
        "</thead><tbody>",
        *rows,
        "</tbody></table>",
        "</div>",
    ]


def _examples(endpoint: VendorEndpoint) -> list[str]:
    """The call built from the params' own examples, and the recorded response when there is one."""
    blocks = []
    if not any(param.required and param.example is None for param in endpoint.params.values()):
        args = {name: param.example for name, param in endpoint.params.items() if param.example is not None}
        params = json.dumps(args, ensure_ascii=False)
        python = (
            f'router.call_data_api("{endpoint.id}", {params})' if args else f'router.call_data_api("{endpoint.id}")'
        )
        mcp = f'call_data_api(endpoint="{endpoint.id}"' + (f", params={params})" if args else ")")
        blocks += [f"```python Python\n{python}\n```", f"```text MCP\n{mcp}\n```"]
    if endpoint.example_response is not None:
        response = json.dumps(endpoint.example_response, indent=2, ensure_ascii=False)
        blocks.append(f"```json Response\n{response}\n```")
    if not blocks:
        return []
    return ["<CodeGroup>", "\n\n".join(blocks), "</CodeGroup>", ""]


def _endpoint(endpoint: VendorEndpoint, vendor: Vendor, peers: list[tuple[Vendor, VendorEndpoint]]) -> list[str]:
    output = _output_panel(endpoint)
    io_class = "wc-io wc-io-split" if output else "wc-io"
    lines = [
        f"### {mdx(endpoint.name)} {{#{anchor(endpoint.id)}}}",
        "",
        '<div className="wc-endpoint">',
        '<div className="wc-endpoint-head">'
        f'{_method(endpoint.method)}<code className="wc-path">{_literal(endpoint.path)}</code>'
        f'<code className="wc-id">{_literal(endpoint.id)}</code>'
        + (f'<span className="wc-write">{_literal("writes")}</span>' if endpoint.writes else "")
        + "</div>",
    ]
    if endpoint.summary:
        lines.append(f'<p className="wc-summary">{text(endpoint.summary)}</p>')
    lines += [f'<div className="{io_class}">', *_input_panel(endpoint), *output, "</div>"]
    meta = [f"<a href={_href(endpoint.docs_url)}>{_literal('Vendor docs')}</a>"]
    others = [
        f'<a href="/{PAGES_DIR}/{peer.vendor}#{anchor(call.id)}">{text(peer.name)}</a>'
        for peer, call in peers[:PEERS_SHOWN]
    ]
    if others:
        meta.append(_literal("Same job: ") + _literal(", ").join(others))
    lines += [f'<div className="wc-endpoint-foot">{_literal(" · ").join(meta)}</div>', "</div>", ""]
    lines += _examples(endpoint)
    if endpoint.notes:
        lines += ["<Note>", *(f"- {mdx(note)}" for note in endpoint.notes), "</Note>", ""]
    return lines


def vendor_page(vendor: Vendor, peers: Peers, icon: str = DEFAULT_ICON) -> str:
    lines = [
        "---",
        f"title: {json.dumps(vendor.name)}",
        f"description: {json.dumps(vendor.summary)}",
        "---",
        "",
        GENERATED_NOTE.format(vendor=vendor.vendor),
        "",
        *_header(vendor, icon),
        *_setup(vendor),
    ]
    if vendor.notes:
        lines += ["## Notes", "", *(f"- {mdx(note)}" for note in vendor.notes), ""]
    lines += ["## Endpoints", "", *_index(vendor)]
    for endpoint in vendor.endpoints:
        others = [pair for pair in peers.get(endpoint.job or "", []) if pair[0].vendor != vendor.vendor]
        lines += _endpoint(endpoint, vendor, others)
    return "\n".join(lines).rstrip() + "\n"
