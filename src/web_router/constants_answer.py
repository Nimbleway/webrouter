# answer()'s `auto`: the configured answer backends, in the order route-eval ranked them.

AUTO_ANSWER_PREFERRED: tuple[str, ...] = _chain("answer", "preferred")
"""The order ``auto`` tries the answer backends you hold a key for.

Generated by ``make chains`` into ``data/chains.json``: route-eval's ranking of
the frozen answer scan, all 300 SimpleQA questions -- accuracy first, and
within the noise floor the cheaper at list price, then the faster. ``brave`` has
no rows there, so it stays last, unmeasured. Never reorder it by hand.
"""

